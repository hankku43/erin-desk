// 運勢分項：工作、人際、金幣（2～5 顆星，跟著等級上下浮動；最少兩顆，沒有凶）
const ASPECTS = ['工作', '人際', '金幣'];

const pickFrom = (arr, rnd) => arr[Math.floor(rnd() * arr.length) % arr.length];
// 挑一個最近沒抽過的（avoid 是最近抽過的清單；試幾次還是重複就算了）
function pickFresh(arr, rnd, avoid) {
  const seen = new Set(avoid || []);
  let x = pickFrom(arr, rnd);
  for (let i = 0; i < 6 && seen.has(x); i++) x = pickFrom(arr, rnd);
  return x;
}
// 抽一次：回傳 { rank, opener, openerRaw, advice, item, color, time, stars }（rnd 是 0～1 的亂數函式；recent＝{opener:[],advice:[],item:[],color:[],time:[]}）
function draw(rnd = Math.random, recent = {}) {
  let r = rnd() * RANKS.reduce((n, x) => n + x.w, 0);
  const rank = RANKS.find((x) => (r -= x.w) < 0) || RANKS[RANKS.length - 1];
  const openerRaw = pickFresh(OPENERS[rank.tier], rnd, recent.opener);
  const opener = openerRaw.replace('{rank}', rank.name);
  const advice = pickFresh([...ADVICE[rank.tier], ...ADVICE.common], rnd, recent.advice);
  const item = pickFresh(ITEMS, rnd, recent.item);
  const color = pickFresh(COLORS, rnd, recent.color);
  const time = pickFresh(TIMES, rnd, recent.time);
  const stars = {};
  for (const a of ASPECTS) stars[a] = Math.max(2, Math.min(5, rank.tier + Math.floor(rnd() * 3) - 1));
  return { rank, opener, openerRaw, advice, item, color, time, stars };
}
// 記住最近抽過的（每種留 keep 個），下次 draw 盡量避開
function remember(recent = {}, d, keep = 20) {
  const out = {};
  const raw = { opener: d.openerRaw || d.opener, advice: d.advice, item: d.item, color: d.color, time: d.time };
  for (const k of Object.keys(raw)) out[k] = [raw[k], ...((recent && recent[k]) || []).filter((x) => x !== raw[k])].slice(0, keep);
  return out;
}

module.exports = { RANKS, OPENERS, ADVICE, ITEMS, COLORS, TIMES, ASPECTS, draw, remember };
