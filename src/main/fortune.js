const pickFrom = (arr, rnd) => arr[Math.floor(rnd() * arr.length) % arr.length];
// 抽一次：回傳 { rank, opener, advice, item }（rnd 是 0～1 的亂數函式）
function draw(rnd = Math.random) {
  let r = rnd() * RANKS.reduce((n, x) => n + x.w, 0);
  const rank = RANKS.find((x) => (r -= x.w) < 0) || RANKS[RANKS.length - 1];
  const opener = pickFrom(OPENERS[rank.tier], rnd).replace('{rank}', rank.name);
  const advice = pickFrom([...ADVICE[rank.tier], ...ADVICE.common], rnd);
  return { rank, opener, advice, item: pickFrom(ITEMS, rnd) };
}

